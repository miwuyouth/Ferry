  const TABLES = { zh, en };
  let current = 'zh';

  // 'system' 时按系统 locale 落到 zh / en 之一；其它语言一律走英文。
  function resolve(pref, systemLocale) {
    if (pref === 'zh' || pref === 'en') return pref;
    return String(systemLocale || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
  }

  function setLang(lang) { current = TABLES[lang] ? lang : 'zh'; }
  function getLang() { return current; }

  function t(key, vars) {
    let s = TABLES[current][key];
    if (s == null) s = zh[key];            // 漏翻时退回中文，别把 key 露到界面上
    if (s == null) return key;
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k])));
  }

  // 渲染层：把标了 data-i18n / data-i18n-ph / data-i18n-title 的节点刷一遍。
  function applyStatic(root) {
    if (typeof document === 'undefined') return;
    const scope = root || document;
    for (const n of scope.querySelectorAll('[data-i18n]')) n.textContent = t(n.dataset.i18n);
    for (const n of scope.querySelectorAll('[data-i18n-ph]')) n.placeholder = t(n.dataset.i18nPh);
    for (const n of scope.querySelectorAll('[data-i18n-title]')) n.title = t(n.dataset.i18nTitle);
    document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en';
  }

  return { t, setLang, getLang, resolve, applyStatic, LANGS: ['system', 'zh', 'en'] };
